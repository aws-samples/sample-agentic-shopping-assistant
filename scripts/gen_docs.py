class _Sink(io.TextIOWrapper):
    """Collects the CDK and jsii console output (warnings, deprecations) that synthesis prints."""

    def __init__(self) -> None:
        super().__init__(io.BytesIO(), encoding="utf-8", errors="replace", write_through=True)

    def text(self) -> str:
        return self.buffer.getvalue().decode("utf-8", "replace")


def render_all() -> dict[Path, str]:
    profiles = synthesize_profiles()
    return {
        OUT / "config-reference.md": render_config_reference(),
        OUT / "cdk-nag-exceptions.md": render_nag_exceptions(profiles),
        OUT / "tool-catalog.md": render_tool_catalog(profiles),
    }


def _stale(path: Path, expected: str) -> str | None:
    name = path.relative_to(ROOT).as_posix()
    if not path.is_file():
        return f"  {name}: missing"
    actual = path.read_text(encoding="utf-8")
    if actual == expected:
        return None
    diff = list(difflib.unified_diff(actual.splitlines(), expected.splitlines(), lineterm="", n=0))[2:]
    changes = [line for line in diff if not line.startswith("@@")]
    added = sum(line.startswith("+") for line in changes)
    removed = len(changes) - added
    first = re.search(r"\+(\d+)", next((line for line in diff if line.startswith("@@")), ""))
    summary = f"  {name}: {added} line{'s' * (added != 1)} to add, {removed} to remove" + (f" (from line {first.group(1)})" if first else "")
    shown = "".join(f"\n      {line[:160]}" for line in changes[:12])
    return summary + shown + ("\n      …" if len(changes) > 12 else "")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docs/generated/ from the code.")
    parser.add_argument("--check", action="store_true", help="exit 1 if a generated file is missing or stale; write nothing")
    args = parser.parse_args(argv)

    out, err = sys.stdout, sys.stderr
    sink = _Sink()
    # jsii relays the CDK's console output from a background thread through sys.stdout/sys.stderr;
    # route it to the sink for the rest of the run and report through the saved streams.
    sys.stdout = sys.stderr = sink
    try:
        documents = render_all()
    except SystemExit as error:
        print(error.code if isinstance(error.code, str) else f"gen_docs: exited {error.code}", file=err)
        return 2
    except ImportError as error:
        print(f"gen_docs: {error}. Run it with the infra environment, from the repository root:\n  {COMMAND}", file=err)
        return 2
    except Exception:  # noqa: BLE001
        print("gen_docs: generating docs/generated/ failed:", file=err)
        traceback.print_exc(file=err)
        captured = [line for line in sink.text().splitlines() if line.strip()][-30:]
        if captured:
            print("CDK output before the failure:\n  " + "\n  ".join(captured), file=err)
        return 2

    strays = sorted(path for path in OUT.glob("*.md") if path not in documents) if OUT.is_dir() else []
    if args.check:
        problems = [problem for path, text in documents.items() if (problem := _stale(path, text))]
        problems += [f"  {path.relative_to(ROOT).as_posix()}: not produced by scripts/gen_docs.py; remove it or add a generator"
                     for path in strays]
        if problems:
            print(f"gen_docs: docs/generated/ is stale. Regenerate it with:\n  {COMMAND}", file=out)
            print("\n".join(problems), file=out)
            return 1
        print("gen_docs: docs/generated/ is up to date", file=out)
        return 0

    OUT.mkdir(parents=True, exist_ok=True)
    for path, text in documents.items():
        name = path.relative_to(ROOT).as_posix()
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            print(f"gen_docs: {name} unchanged", file=out)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"gen_docs: wrote {name}", file=out)
    for path in strays:
        print(f"gen_docs: {path.relative_to(ROOT).as_posix()} is not generated; remove it or add a generator", file=err)
    return 0


if __name__ == "__main__":
    sys.exit(main())
