# ── Markdown helpers ────────────────────────────────────────────────────


def link(path: Path, text: str | None = None) -> str:
    """A link from docs/generated/ to a file in the repository."""
    target = Path(*([".."] * len(OUT.relative_to(ROOT).parts)), path.relative_to(ROOT)).as_posix()
    return f"[{text or path.relative_to(ROOT).as_posix()}]({target})"


def anchor(title: str) -> str:
    return "#" + github_slug(title)


def code(text: object) -> str:
    text = str(text)
    fence = "``" if "`" in text else "`"
    pad = " " if text.startswith("`") or text.endswith("`") else ""
    return f"{fence}{pad}{text}{pad}{fence}"


def prose(text: str) -> str:
    """Plain text as markdown: inline code kept, and characters that would start HTML or emphasis escaped."""
    parts = re.split(r"(`+[^`]*`+)", text)
    return "".join(part if index % 2 else part.replace("<", "&lt;").replace("*", "\\*")
                   for index, part in enumerate(parts))


def cell(text: str) -> str:
    """Prose for a table cell, on one line."""
    return prose(" ".join(str(text).split()))


def table(header: list[str], rows: list[list[str]]) -> list[str]:
    """A markdown table; a pipe inside a cell (code spans included) is escaped so it can't split the cell."""
    def escape(text: str) -> str:
        return re.sub(r"(?<!\\)\|", r"\\|", text)

    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    lines += ["| " + " | ".join(escape(value) for value in row) + " |" for row in rows]
    return lines


DEFINITION = re.compile(r"^([A-Za-z_][\w-]*): (.*)$")


def docstring_markdown(doc: str | None) -> list[str]:
    """A docstring as paragraphs. A paragraph of `term: text` lines (two or more) becomes a list."""
    if not doc:
        return []
    blocks = []
    for paragraph in re.split(r"\n\s*\n", inspect.cleandoc(doc)):
        lines = paragraph.splitlines()
        terms = [line for line in lines if DEFINITION.match(line)]
        if len(terms) >= 2 and DEFINITION.match(lines[0]) and all(DEFINITION.match(line) or line[:1].isspace() for line in lines):
            items: list[list[str]] = []
            for line in lines:
                match = DEFINITION.match(line)
                if match:
                    items.append([f"{code(match.group(1))}: {prose(match.group(2))}"])
                else:
                    items[-1].append(prose(line.strip()))
            blocks.append("\n".join("- " + " ".join(item) for item in items))
        else:
            blocks.append(prose(" ".join(line.strip() for line in lines)))
    return blocks


