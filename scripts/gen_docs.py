# Dev+ and Prod+ turn on every optional stack the committed templates leave off, so their exceptions
# are listed too; Dev+ also turns on the saved-items sample, which Prod rejects. Mirrors the offline
# profile matrix in packages/infra/tests/test_profiles.py.
OPTIONAL = {
    "tools": {"productSearch": {"provider": "opensearch"}},
    "memory": {"longTerm": True},
    "evaluations": {"enabled": True},
    "operations": {"transactionSearchReady": True, "captureContent": True,
                   "traceLogGroup": "/aws/bedrock-agentcore/runtimes/example-DEFAULT"},
}
DEV_ONLY = {"gateway": {"savedItemsSample": True}}
PROFILES = (("Dev", "dev.toml", False), ("Prod", "prod.toml", False), ("Dev+", "dev.toml", True), ("Prod+", "prod.toml", True))


def _optional(toml: str) -> dict:
    """The settings a + profile adds to its template."""
    return _merge(_merge({}, OPTIONAL), DEV_ONLY) if toml == "dev.toml" else OPTIONAL


@dataclass(frozen=True)
class Suppression:
    stack: str  # the stack name without the namespace, e.g. "Gateway"
    path: str  # construct path inside the stack; "" for a stack-level suppression
    rule: str
    reason: str
    applies_to: tuple[str, ...]


@dataclass
class SynthStack:
    role: str
    name: str
    template: dict
    paths: dict[str, str]  # logical ID -> construct path inside the stack


@dataclass
class Profile:
    label: str
    toml: str  # the config template, e.g. "dev.toml"
    optional: bool
    config: object
    stacks: list[SynthStack]


def _merge(base: dict, overrides: dict) -> dict:
    for key, value in overrides.items():
        if isinstance(value, dict):
            _merge(base.setdefault(key, {}), value)
        else:
            base[key] = value
    return base


def _flatten(overrides: dict, prefix: str = "") -> list[str]:
    out = []
    for key, value in overrides.items():
        if isinstance(value, dict):
            out += _flatten(value, f"{prefix}{key}.")
        else:
            out.append(f"{prefix}{key} = {toml_value(value)}")
    return out


def synthesize_profiles() -> list[Profile]:
    import aws_cdk as cdk
    from app import build_app
    from config.loader import Config, load_config

    profiles = []
    for label, toml, optional in PROFILES:
        config = load_config(INFRA / "config" / toml)
        if optional:
            config = Config.model_validate(_merge(config.model_dump(by_alias=True), _optional(toml)))
        app = build_app(config, offline=True)
        assembly = app.synth()
        stacks = []
        for stack in app.node.children:
            if not isinstance(stack, cdk.Stack):
                continue
            paths = {}
            for node in stack.node.find_all():
                if cdk.CfnElement.is_cfn_element(node):
                    paths[stack.get_logical_id(node)] = node.node.path.removeprefix(stack.node.path + "/")
            role = stack.node.id.removeprefix(config.ns) or stack.node.id
            template_body = assembly.get_stack_artifact(stack.artifact_id).template
            stacks.append(SynthStack(role, stack.stack_name, template_body, paths))
        profiles.append(Profile(label, toml, optional, config, stacks))
    return profiles


# ── cdk-nag exceptions ──────────────────────────────────────────────────


def _suppressions(stack: SynthStack) -> list[Suppression]:
    def read(metadata: dict, path: str) -> list[Suppression]:
        rules = (metadata or {}).get("cdk_nag", {}).get("rules_to_suppress", [])
        out = []
        for rule in rules:
            applies = rule.get("applies_to") or rule.get("appliesTo") or []
            applies = tuple(f"regex {item['regex']}" if isinstance(item, dict) and "regex" in item else str(item) for item in applies)
            out.append(Suppression(stack.role, path, rule.get("id", "?"), " ".join(str(rule.get("reason", "")).split()), applies))
        return out

    found = read(stack.template.get("Metadata"), "")
    for logical_id, resource in stack.template.get("Resources", {}).items():
        found += read(resource.get("Metadata"), stack.paths.get(logical_id, logical_id))
    return found


