@dataclass
class ModelSource:
    """What loader.py says about one model class beyond what pydantic keeps."""

    comments: dict[str, str] = field(default_factory=dict)  # field name -> comment text
    raises: list[tuple[str, str]] = field(default_factory=list)  # (method, error message), in source order


def _comment_lines(source: str) -> tuple[dict[int, str], dict[int, str]]:
    """Comments by line: those alone on their line, and those trailing code."""
    alone, trailing = {}, {}
    for token in tokenize.generate_tokens(io.StringIO(source).readline):
        if token.type == tokenize.COMMENT:
            text = token.string.lstrip("#").strip()
            (trailing if token.line[: token.start[1]].strip() else alone)[token.start[0]] = text
    return alone, trailing


def _message(node: ast.expr) -> str | None:
    """The text of an error message literal; f-string fields render as {expression}."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.JoinedStr):
        parts = []
        for value in node.values:
            if isinstance(value, ast.Constant):
                parts.append(str(value.value))
            elif isinstance(value, ast.FormattedValue):
                parts.append("{" + ast.unparse(value.value).removeprefix("self.") + "}")
        return "".join(parts)
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        left, right = _message(node.left), _message(node.right)
        return left + right if left is not None and right is not None else None
    return None


def read_model_sources(path: Path) -> dict[str, ModelSource]:
    source = path.read_text(encoding="utf-8")
    alone, trailing = _comment_lines(source)
    models = {}
    for node in ast.parse(source).body:
        if not isinstance(node, ast.ClassDef):
            continue
        info = ModelSource()
        for item in node.body:
            if isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
                above, line = [], item.lineno - 1
                while line in alone:
                    above.insert(0, alone[line])
                    line -= 1
                if item.lineno in trailing:
                    above.append(trailing[item.lineno])
                if above:
                    # A path wrapped onto the next comment line rejoins without a space.
                    info.comments[item.target.id] = re.sub(r"/ (?=\S)", "/", " ".join(above))
            elif isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                for raised in ast.walk(item):
                    if (isinstance(raised, ast.Raise) and isinstance(raised.exc, ast.Call) and raised.exc.args
                            and getattr(raised.exc.func, "id", None) in ("ValueError", "TypeError")):
                        message = _message(raised.exc.args[0])
                        if message:
                            info.raises.append((raised.lineno, item.name, message))
        info.raises = [(method, message) for _, method, message in sorted(info.raises)]
        models[node.name] = info
    return models


def _unwrap_optional(annotation):
    if typing.get_origin(annotation) in (typing.Union, types.UnionType):
        options = [arg for arg in typing.get_args(annotation) if arg is not type(None)]
        if len(options) == 1:
            return options[0]
    return annotation


def _is_model(annotation) -> bool:
    from pydantic import BaseModel

    return inspect.isclass(annotation) and issubclass(annotation, BaseModel)


def submodel(annotation):
    """(model class, is an array of tables) for a field holding a nested model, else (None, False)."""
    annotation = _unwrap_optional(annotation)
    if typing.get_origin(annotation) in (list, tuple, set, frozenset):
        args = typing.get_args(annotation)
        if args and _is_model(args[0]):
            return args[0], True
    if _is_model(annotation):
        return annotation, False
    return None, False


SCALARS = {str: "string", int: "integer", float: "float", bool: "boolean", dict: "table", list: "array"}
NAMED_TYPES = {"IPvAnyNetwork": "IP network (CIDR)", "IPvAnyAddress": "IP address", "AnyUrl": "URL", "HttpUrl": "URL"}
PLURALS = {"string": "strings", "integer": "integers", "float": "floats", "boolean": "booleans", "table": "tables",
           "IP network (CIDR)": "IP networks (CIDR)", "IP address": "IP addresses", "URL": "URLs"}


def toml_type(annotation) -> str:
    annotation = _unwrap_optional(annotation)
    origin, args = typing.get_origin(annotation), typing.get_args(annotation)
    if origin is typing.Literal:
        kinds = {toml_type(type(value)) for value in args}
        return kinds.pop() if len(kinds) == 1 else "value"
    if origin in (list, tuple, set, frozenset):
        item = toml_type(args[0]) if args else "value"
        return f"array of {PLURALS.get(item, item)}"
    if origin is dict:
        value = toml_type(args[1]) if len(args) == 2 else "value"
        return f"table of {PLURALS.get(value, value)}"
    if annotation in SCALARS:
        return SCALARS[annotation]
    if _is_model(annotation):
        return "table"
    if inspect.isclass(annotation) and issubclass(annotation, enum.Enum):
        return toml_type(type(next(iter(annotation)).value))
    name = getattr(annotation, "__name__", str(annotation))
    return NAMED_TYPES.get(name, name)


def toml_value(value) -> str:
    if isinstance(value, enum.Enum):
        value = value.value
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (list, tuple, set, frozenset)):
        return "[" + ", ".join(toml_value(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{key} = {toml_value(item)}" for key, item in value.items()) + " }" if value else "{}"
    return str(value)


def default_text(info) -> str:
    if info.is_required():
        return "required"
    try:
        value = info.get_default(call_default_factory=True)
    except Exception:  # noqa: BLE001  (a factory that needs the other fields' values)
        return "computed"
    if value is None:
        return "not set"
    if _is_model(type(value)):
        return "defaults below"
    return code(toml_value(value))


def allowed_text(info) -> str:
    annotation = _unwrap_optional(info.annotation)
    each = typing.get_origin(annotation) in (list, tuple, set, frozenset)
    item = _unwrap_optional(typing.get_args(annotation)[0]) if each and typing.get_args(annotation) else annotation
    bits = []
    if typing.get_origin(item) is typing.Literal:
        values = typing.get_args(item)
    elif inspect.isclass(item) and issubclass(item, enum.Enum):
        values = tuple(member.value for member in item)
    else:
        values = ()
    if values:
        bits.append(("each one of " if each else "") + ", ".join(code(toml_value(value)) for value in values))
    bounds = {}
    for meta in info.metadata:
        for name in ("gt", "ge", "lt", "le", "multiple_of", "min_length", "max_length", "pattern"):
            if getattr(meta, name, None) is not None:
                bounds[name] = getattr(meta, name)
    if "ge" in bounds and "le" in bounds:
        bits.append(f"{bounds['ge']!r} to {bounds['le']!r}")
    else:
        bits += [f"{sign} {bounds[name]!r}" for name, sign in (("ge", ">="), ("gt", ">"), ("le", "<="), ("lt", "<")) if name in bounds]
    if "multiple_of" in bounds:
        bits.append(f"a multiple of {bounds['multiple_of']!r}")
    array = each or "array" in toml_type(info.annotation)
    for name, word in (("min_length", "at least"), ("max_length", "at most")):
        if name in bounds:
            count = bounds[name]
            unit = ("entry" if count == 1 else "entries") if array else ("character" if count == 1 else "characters")
            bits.append(f"{word} {count} {unit}")
    if "pattern" in bounds:
        bits.append(f"matches {code(bounds['pattern'])}")
    return "; ".join(bits)


@dataclass
class Section:
    path: tuple[str, ...]  # TOML keys from the root
    model: type
    array: bool
    info: object | None  # the parent's field, None for the root

    @property
    def title(self) -> str:
        name = ".".join(self.path)
        return code(f"[[{name}]]" if self.array else f"[{name}]")


def toml_key(name: str, info) -> str:
    alias = info.validation_alias if isinstance(info.validation_alias, str) else info.alias
    return alias or name


def collect_sections(model, path=(), array=False, info=None, depth=0) -> list[Section]:
    if depth > 8:
        raise SystemExit(f"gen_docs: config models nest too deeply at {'.'.join(path)}")
    sections = [Section(path, model, array, info)]
    for name, child in model.model_fields.items():
        nested, is_array = submodel(child.annotation)
        if nested:
            sections += collect_sections(nested, path + (toml_key(name, child),), is_array, child, depth + 1)
    return sections


def _summary(section: Section) -> str:
    """The first paragraph of the model's docstring."""
    doc = section.model.__dict__.get("__doc__")
    return " ".join(inspect.cleandoc(doc).split("\n\n")[0].split()) if doc else ""


def _lineage(model, sources: dict[str, ModelSource]) -> list[tuple[str, ModelSource]]:
    """(class name, source notes) for a model and the loader.py classes it inherits from, nearest first."""
    return [(cls.__name__, sources[cls.__name__]) for cls in model.__mro__
            if cls.__module__ == model.__module__ and cls.__name__ in sources]


def render_config_reference() -> str:
    from config import loader

    loader_path = Path(loader.__file__).resolve()
    sources = read_model_sources(loader_path)
    sections = collect_sections(loader.Config)
    by_path = {section.path: section for section in sections}
    templates = sorted((INFRA / "config").glob("*.toml"))
    strict = all(section.model.model_config.get("extra") == "forbid" for section in sections)

    lines = [HEADER, "", "# Configuration reference", ""]
    lines += ["> " + block if block else ">" for block in "\n\n".join(docstring_markdown(loader.__doc__)).split("\n")]
    lines += [
        "",
        f"Every key the CDK app reads, from the pydantic models in {link(loader_path)} and the comments above "
        f"their fields. Templates: {', '.join(link(path, path.relative_to(INFRA).as_posix()) for path in templates)}."
        + (" Unknown keys fail validation." if strict else "")
        + " Sections are in alphabetical order; keys keep the order of loader.py. Defaults and allowed values are TOML literals.",
        "",
        "## Sections",
        "",
    ]
    top = sorted((s for s in sections if len(s.path) == 1), key=lambda s: s.path[0].lower())
    lines += table(["Section", "Required", "Summary"], [
        [f"[{section.title}]({anchor(section.title)})", "yes" if section.info.is_required() else "no",
         cell(_summary(section))] for section in top
    ])

    def render(section: Section) -> None:
        lineage = _lineage(section.model, sources)
        lines.extend(["", "#" * min(len(section.path) + 1, 6) + " " + section.title, ""])
        intro = "An array of tables: repeat the header once per entry." if section.array else (
            "Required." if section.info.is_required() else "Optional.")
        lines.extend([intro, ""])
        for block in docstring_markdown(section.model.__dict__.get("__doc__")):
            lines.extend([block, ""])
        rows = []
        for name, info in section.model.model_fields.items():
            key = toml_key(name, info)
            nested, is_array = submodel(info.annotation)
            if nested:
                child = by_path[section.path + (key,)]
                kind = f"{'array of tables' if is_array else 'table'}: [{child.title}]({anchor(child.title)})"
            else:
                kind = toml_type(info.annotation)
            description = info.description or next((s.comments[name] for _, s in lineage if name in s.comments), "")
            rows.append([code(key), kind, default_text(info), allowed_text(info), cell(description)])
        lines.extend(table(["Key", "Type", "Default", "Allowed values", "Description"], rows))
        raises = [(owner, method, message) for owner, source in lineage for method, message in source.raises]
        if raises:
            lines.extend(["", f"Checks in {link(loader_path, 'loader.py')}, as the errors they raise:", ""])
            lines.extend(f"- {code(owner + '.' + method)}: {prose(message)}" for owner, method, message in raises)
        children = sorted((s for s in sections if len(s.path) == len(section.path) + 1 and s.path[:-1] == section.path),
                          key=lambda s: s.path[-1].lower())
        for child in children:
            render(child)

    for section in top:
        render(section)

    root = [message for _, source in _lineage(loader.Config, sources) for _, message in source.raises]
    if root:
        lines.extend(["", "## Cross-section checks", "",
                      f"{code(loader.Config.__name__)} validates the whole file after the sections. The errors it raises "
                      f"({link(loader_path, 'loader.py')}):", ""])
        lines.extend(f"- {prose(message)}" for message in root)
    return "\n".join(lines) + "\n"


