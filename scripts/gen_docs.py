def render_nag_exceptions(profiles: list[Profile]) -> str:
    labels: dict[Suppression, set[str]] = defaultdict(set)
    stack_names: dict[str, set[str]] = defaultdict(set)
    for profile in profiles:
        for stack in profile.stacks:
            stack_names[stack.role].add(stack.name)
            for suppression in _suppressions(stack):
                labels[suppression].add(profile.label)

    def shown(found: set[str]) -> str:
        # A label with + means the exception appears only with the optional stacks on.
        return ", ".join(stage if stage in found else stage + "+" for stage in ("Dev", "Prod") if stage in found or stage + "+" in found)

    groups: dict[tuple, list[str]] = defaultdict(list)
    for suppression, found in labels.items():
        key = (suppression.stack, suppression.rule, suppression.reason, suppression.applies_to, shown(found))
        groups[key].append(suppression.path)

    lines = [HEADER, "", "# cdk-nag exceptions", "", *NAG_INTRO, "", "Profiles synthesized:", ""]
    for label, toml, optional in PROFILES:
        if not optional:
            lines.append(f"- **{label}**: {link(INFRA / 'config' / toml, 'config/' + toml)} as committed.")
    lines.append("- **Dev+**, **Prod+**: the same templates with every optional stack on: "
                 + ", ".join(code(item) for item in _flatten(OPTIONAL)) + ". Dev+ also sets "
                 + ", ".join(code(item) for item in _flatten(DEV_ONLY)) + ", which Prod rejects. "
                 "A row marked only Dev+ or Prod+ appears only with those settings.")
    quiet = sorted(role for role in stack_names if not any(key[0] == role for key in groups))
    if quiet:
        lines += ["", "Stacks with no exceptions: " + ", ".join(code(role) for role in quiet) + "."]
    for role in sorted({key[0] for key in groups}, key=str.lower):
        lines += ["", f"## {role}", "", "Stacks: " + ", ".join(code(name) for name in sorted(stack_names[role])) + ".", ""]
        rows = []
        for key in sorted((key for key in groups if key[0] == role),
                          key=lambda key: (min(groups[key]) != "", min(groups[key]), key[1], key[2], key[3], key[4])):
            _, rule, reason, applies_to, found = key
            paths = sorted(groups[key])
            where = "stack-level" if paths == [""] else "<br>".join(code(path) if path else "stack-level" for path in paths)
            rows.append([where, code(rule), found, cell(reason), "<br>".join(code(item) for item in applies_to)])
        lines += table(["Resource", "Rule", "Profiles", "Reason", "Applies to"], rows)
    return "\n".join(lines) + "\n"


